import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root = process.cwd();
const base = 'acceptance/20261016-expanded/session-c';
const project = 'acceptance/20261016-expanded/works/潮汐信号';
const [label, command, ...args] = process.argv.slice(2);
if (!label || !command || !/^[a-zA-Z0-9_-]+$/.test(label)) throw new Error('label command required');
const dir = path.join(root, base, 'cli');
fs.mkdirSync(dir, {recursive:true});
const prefix = path.join(dir, label);
if (fs.existsSync(prefix+'.json')) throw new Error('log label exists');
const argv = [project+'/.writer/tool/bin/ai-writer.mjs',command,'--project',project,...args];
const started = new Date().toISOString();
const r = spawnSync(process.execPath,argv,{cwd:root,encoding:null,maxBuffer:64*1024*1024});
fs.writeFileSync(prefix+'.stdout',r.stdout??Buffer.alloc(0));
fs.writeFileSync(prefix+'.stderr',r.stderr??Buffer.alloc(0));
fs.writeFileSync(prefix+'.json',JSON.stringify({executable:process.execPath,argv,cwd:root,started,finished:new Date().toISOString(),exit_code:r.status,signal:r.signal,error:r.error?.message??null},null,2)+'\n');
process.stdout.write(r.stdout??Buffer.alloc(0));
process.stderr.write(r.stderr??Buffer.alloc(0));
process.exitCode=r.status??1;
