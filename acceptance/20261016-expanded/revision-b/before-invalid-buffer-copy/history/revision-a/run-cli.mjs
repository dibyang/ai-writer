import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root='D:/work/other/ai-writer';
const stage=path.join(root,'acceptance/20261016-expanded/revision-a');
const project=path.join(root,'acceptance/20261016-expanded/works/潮汐信号');
fs.mkdirSync(path.join(stage,'cli'),{recursive:true});
const [label,...args]=process.argv.slice(2);
if(!label || !args.length) throw new Error('label and CLI args required');
const argv=[path.join(root,'bin/ai-writer.mjs'),...args];
if(!args.includes('--project') && !args.includes('--help')) argv.push('--project',project);
const started=new Date().toISOString();
const r=spawnSync(process.execPath,argv,{cwd:root,encoding:'utf8',maxBuffer:64*1024*1024});
const meta={started,ended:new Date().toISOString(),cwd:root,executable:process.execPath,argv,exit_code:r.status,signal:r.signal,error:r.error?String(r.error):null,stdout:r.stdout??'',stderr:r.stderr??''};
const name=path.join(stage,'cli',label);
if(fs.existsSync(name+'.json')) throw new Error('log already exists: '+label);
fs.writeFileSync(name+'.json',JSON.stringify(meta,null,2)+'\n');
fs.writeFileSync(name+'.stdout',meta.stdout);
fs.writeFileSync(name+'.stderr',meta.stderr);
process.stdout.write(meta.stdout); process.stderr.write(meta.stderr);
console.log('\nCLI_EXIT_CODE='+r.status);
process.exitCode=r.status??1;
