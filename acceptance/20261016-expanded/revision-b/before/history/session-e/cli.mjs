import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=process.cwd();
const stage='acceptance/20261016-expanded/session-e';
const work='acceptance/20261016-expanded/works/潮汐信号';
const [label,...args]=process.argv.slice(2);
if(!/^[a-z0-9-]+$/.test(label||'')) throw new Error('label required');
fs.mkdirSync(path.join(root,stage,'logs'),{recursive:true});
const argv=[`${work}/.writer/tool/bin/ai-writer.mjs`,...args,'--project',work];
const started=new Date().toISOString();
const r=spawnSync(process.execPath,argv,{cwd:root,encoding:'utf8',maxBuffer:32*1024*1024});
const base=path.join(root,stage,'logs',label);
if(fs.existsSync(base+'.json')) throw new Error('log exists: '+label);
fs.writeFileSync(base+'.stdout',r.stdout||'','utf8');
fs.writeFileSync(base+'.stderr',r.stderr||'','utf8');
fs.writeFileSync(base+'.json',JSON.stringify({started,finished:new Date().toISOString(),cwd:root,executable:process.execPath,argv,exit_code:r.status,signal:r.signal,error:r.error?String(r.error):null},null,2)+'\n');
process.stdout.write(r.stdout||''); process.stderr.write(r.stderr||'');
process.exitCode=r.status??1;
