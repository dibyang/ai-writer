import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(dir,'../../..');
const logdir=path.join(dir,'cli-logs');
fs.mkdirSync(logdir,{recursive:true});
const args=process.argv.slice(2);
const num=String(fs.readdirSync(logdir).filter(x=>x.endsWith('.meta.json')).length+1).padStart(3,'0');
const stem=path.join(logdir,`${num}-${args[0]||'help'}`);
const argv=[path.join(root,'bin/ai-writer.mjs'),...args];
const start=new Date().toISOString();
const r=spawnSync(process.execPath,argv,{cwd:root,encoding:null,maxBuffer:16*1024*1024});
fs.writeFileSync(stem+'.stdout',r.stdout||Buffer.alloc(0));
fs.writeFileSync(stem+'.stderr',r.stderr||Buffer.alloc(0));
fs.writeFileSync(stem+'.meta.json',JSON.stringify({start,end:new Date().toISOString(),cwd:root,executable:process.execPath,argv,exit_code:r.status,signal:r.signal,error:r.error?.message||null},null,2)+'\n');
process.stdout.write(r.stdout||'');
process.stderr.write(r.stderr||'');
process.exitCode=r.status??2;
