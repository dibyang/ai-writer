import {spawnSync} from 'node:child_process';
import {mkdirSync,writeFileSync,appendFileSync,existsSync} from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const base='acceptance/20261016-expanded/session-d';
const project='acceptance/20261016-expanded/works/潮汐信号';
const [label,...args]=process.argv.slice(2);
if(!label||!/^[a-z0-9-]+$/.test(label)) throw Error('label required');
mkdirSync(path.join(base,'cli'),{recursive:true});
const prefix=path.join(base,'cli',label);
if(existsSync(prefix+'.meta.json')) throw Error('refuse log overwrite');
const argv=[path.join(project,'.writer/tool/bin/ai-writer.mjs'),...args,'--project',project];
const started=new Date().toISOString();
const r=spawnSync(process.execPath,argv,{cwd:root,encoding:null,maxBuffer:20*1024*1024});
writeFileSync(prefix+'.stdout',r.stdout??Buffer.alloc(0));
writeFileSync(prefix+'.stderr',r.stderr??Buffer.alloc(0));
const meta={cwd:root,executable:process.execPath,argv,started,finished:new Date().toISOString(),exit_code:r.status,signal:r.signal,error:r.error?String(r.error):null};
writeFileSync(prefix+'.meta.json',JSON.stringify(meta,null,2)+'\n');
appendFileSync(path.join(base,'cli-index.jsonl'),JSON.stringify({label,...meta})+'\n');
process.stdout.write(r.stdout??'');process.stderr.write(r.stderr??'');process.exitCode=r.status??1;
