import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { stage, work, load, state, put, sha, cli, input } from './helpers.mjs';
const old=load(path.join(stage,'before/work/.writer/state.json')), s=state();
const commitBinding=s.committed_revisions.at(-1), commit=load(path.join(work,commitBinding.ref));
const result=load(path.join(stage,'commit-result.json'));
assert.equal(result.status,'completed');assert.equal(result.revision,s.revision);assert.equal(commit.base_revision+1,s.revision);
assert.deepEqual(s.units.slice(0,4),old.units.slice(0,4));
for(const i of [0,1,2,3,5])assert.equal(sha(fs.readFileSync(path.join(work,s.units[i].draft))),old.units[i].sha256);
assert.equal(sha(fs.readFileSync(path.join(work,s.units[4].draft))),'b819ba8107ddbc052709f26480638e6fa5b9fe14450e5f3570e832d46efbd307');
cli('native-two-26-apply-adopted',['review-issues','apply','--input',input('apply-adopted',{expected_revision:s.revision,operation_id:'native-two-apply-only-repeated-character',id:'NATIVE_C_READABILITY_01',commit_id:commit.id,reason:'synthetic-acceptance：已完成真实主稿事务，仅第5章原句删一个里；绑定采用时旧稿与当前新稿及本次commit。第6章等价重登，尚未执行意见verify，保留和延期项不记applied。'})]);
put(path.join(stage,'after-apply-state.json'),state());
const applied=state();
assert.equal(applied.review_workflow.issues.NATIVE_C_READABILITY_01.status,'applied');
assert.equal(applied.review_workflow.issues.NATIVE_C_STYLE_02.status,'retained');
assert.equal(applied.review_workflow.issues.NATIVE_C_PACING_03.status,'deferred');
cli('native-two-27-pause',['workflow','set','--input',input('workflow-pause',{expected_revision:applied.revision,operation_id:'native-two-pause-after-apply',author_evidence:load(path.join(stage,'author-evidence.json')),workflow:{stage:'paused',task:'synthetic-acceptance：5–6修订已commit并仅采用意见applied；正式暂停，下一独立会话先完整连读全六章新稿再复核意见；不verify，不写7',authorization:{allowed_actions:['discuss','plan'],draft_range:null,revise_range:null,stop_conditions:['保持暂停；全六章新稿复核交下一独立会话，本会话不verify、不写第7章；任何后续修订须新授权']},planning:applied.governance.planning}})]);
cli('native-two-28-issues-applied',['review-issues','list']);
cli('native-two-29-final-check',['check']);
cli('native-two-30-final-status',['status']);
cli('native-two-31-next-discussion',['context','--purpose','discussion']);
cli('native-two-32-identify-final',['tool','identify'],null);
