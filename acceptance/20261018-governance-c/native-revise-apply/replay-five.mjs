import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { stage, work, load, state, put, sha, cli, input } from './helpers.mjs';
const a=load(path.join(stage,'session-access.json')), w=a.workspace;
const s=state(work), before=load(path.join(stage,'before/work/.writer/state.json'));
assert.equal(s.revision,13);
for(const u of before.units) assert.equal(sha(fs.readFileSync(path.join(work,u.draft))),u.sha256);
const u5=before.units[4], old5=fs.readFileSync(path.join(stage,'before/work',u5.draft));
const new5=fs.readFileSync(path.join(w,u5.draft));
assert.equal(new5.toString('utf8'),old5.toString('utf8').replace('布袋里里','布袋里'));
assert.equal(sha(fs.readFileSync(path.join(w,before.units[5].draft))),before.units[5].sha256);
put(path.join(stage,'branch-edit-check.json'),{main_revision:s.revision,main_bodies_unchanged:true,single_body_edit:true,unit5_before_sha256:sha(old5),unit5_after_sha256:sha(new5),unit5_bytes_before:old5.length,unit5_bytes_after:new5.length,unit6_unchanged:true});
const plan=load(path.join(w,'大纲/单元/0005.json'));
plan.forbidden[0]='仅按第二阶段模拟作者原话修正布袋里里一处；其余正文与人物声音保留';
plan.beats[2]='周梅明确今夜钥匙仍由林禾保管；第二阶段仅删指定重复字，不改动作事实';
cli('native-two-12-plan-5-sync',['plan','--input',input('plan-5-scope-sync',plan),'--revision-token',a.token],w);
const r=cli('native-two-13-replay-input-5',['revision','replay-input','--unit','5','--revision-token',a.token,'--out','.writer/drafts/native-two-replay-5-pending.json'],w);
put(path.join(stage,'replay-5-response.json'),r);
const preview=cli('native-two-14-preview-5-unfinished-denied',['record-preview','--input',path.join(w,'.writer/drafts/native-two-replay-5-pending.json'),'--revision-token',a.token],w,1);
assert.equal(preview.ok,false);
console.log('unfinished preview rejected; raw state snapshots kept by capture');
