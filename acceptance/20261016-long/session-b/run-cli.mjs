import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, appendFileSync, existsSync } from 'node:fs';
import { resolve, relative } from 'node:path';
const root = process.cwd();
const stage = resolve(root, 'acceptance/20261016-long/session-b');
const project = 'acceptance/20261016-long/works/雨线档案';
const [label, ...tail] = process.argv.slice(2);
if (!/^[a-z0-9-]+$/.test(label || '')) throw new Error('safe unique label required');
if (tail.includes('--project')) throw new Error('runner supplies explicit project');
mkdirSync(resolve(stage, 'commands'), { recursive: true });
const dest = resolve(stage, 'commands', label);
if (existsSync(dest + '.json')) throw new Error('label already used');
const argv = ['bin/ai-writer.mjs', ...tail, '--project', project];
const started = new Date().toISOString();
const result = spawnSync(process.execPath, argv, { cwd: root, encoding: 'utf8', windowsHide: true, maxBuffer: 16 * 1024 * 1024 });
const log = { executable: process.execPath, argv, cwd: root, started, ended: new Date().toISOString(), exit_code: result.status, signal: result.signal, error: result.error?.message ?? null, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
writeFileSync(dest + '.json', JSON.stringify(log, null, 2) + '\n', 'utf8');
writeFileSync(dest + '.stdout.txt', log.stdout, 'utf8');
writeFileSync(dest + '.stderr.txt', log.stderr, 'utf8');
appendFileSync(resolve(stage, 'commands.jsonl'), JSON.stringify({ label, ...log }) + '\n', 'utf8');
process.stdout.write(log.stdout); process.stderr.write(log.stderr);
console.log(JSON.stringify({ evidence: relative(root, dest + '.json'), exit_code: result.status }));
process.exitCode = result.status ?? 1;
