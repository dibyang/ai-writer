import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url)), work=path.join(base,'work');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const state=read(path.join(work,'.writer/state.json'));
const prior=read(path.join(base,'../20261027-hundred-0100-aj/work/.writer/state.json'));
const manifest=read(path.join(base,'export-final/manifest.json'));
assert.equal(state.units.length,118); assert.equal(prior.units.length,112);
const drafts=state.units.map(u=>{const b=fs.readFileSync(path.join(work,u.draft));assert.equal(sha(b),u.sha256);return b.toString('utf8');});
const changed=prior.units.filter((u,i)=>u.sha256!==state.units[i].sha256).map(u=>u.unit);
assert.deepEqual(changed,[110,112]);
assert.equal(manifest.status,'draft-export');assert.equal(manifest.quality_review,'required');assert.deepEqual(manifest.included_units,state.units.map(u=>u.unit));
const actual=fs.readFileSync(path.join(base,'export-final/manuscript.md'),'utf8');
const expected=drafts.map(x=>x.trim()).join('\n\n---\n\n')+'\n';assert.equal(actual,expected);
const count=s=>(s.replace(/^.*(?:\r?\n|$)/,'').match(/\p{Script=Han}/gu)||[]).length;
const lengths=state.units.slice(106).map((u,i)=>({unit:u.unit,han:count(drafts[106+i])}));
const out={ok:true,revision:state.revision,units:state.units.length,prior_units:prior.units.length,changed_prior_units:changed,all_registered_body_hashes_match:true,export_matches_all_drafts:true,export_sha256:sha(Buffer.from(actual)),export_status:manifest.status,quality_review:manifest.quality_review,lengths};
fs.writeFileSync(path.join(base,'final-independent-check.json'),JSON.stringify(out,null,2)+'\n',{flag:'wx'});console.log(JSON.stringify(out));
