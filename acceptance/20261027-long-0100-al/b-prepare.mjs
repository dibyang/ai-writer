import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const base=path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/,'$1'));
const root=path.join(base,'work');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const json=p=>JSON.parse(read(p));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const write=(p,v)=>fs.writeFileSync(path.join(root,p),JSON.stringify(v,null,2)+'\n',{flag:'wx'});
const state=json('.writer/state.json');
const scan=(d)=>fs.readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?scan(path.join(d,e.name)):[path.join(d,e.name)]);
const old=scan(path.join(root,'正文')).filter(p=>p.endsWith('.md')).map(p=>{const b=fs.readFileSync(p);return {path:path.relative(root,p).replaceAll('\\','/'),sha256:sha(b)};});
fs.writeFileSync(path.join(base,'session-b-before.json'),JSON.stringify({revision:state.revision,state_sha256:sha(fs.readFileSync(path.join(root,'.writer/state.json'))),drafts:old},null,2)+'\n',{flag:'wx'});
const w=json('研究/AL-a-workflow.json');
w.expected_revision=state.revision;w.operation_id='AL-session-b-drafting-115-116';
const evidence=read('研究/AL-b-session-instruction.md');
w.author_evidence={quote:evidence.trim(),local_source:'研究/AL-b-session-instruction.md',source_sha256:sha(Buffer.from(evidence)),locator:'本独立会话用户明确指令的本地逐字摘录；无可核会话ID',recorded_by:'session-b 独立Codex会话'};
