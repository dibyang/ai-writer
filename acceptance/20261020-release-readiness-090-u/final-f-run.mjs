import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const base=path.resolve('acceptance/20261020-release-readiness-090-u');
const root=path.join(base,'scenario-final/东岸末班船');
const [label,...args]=process.argv.slice(2);
if(!/^[a-z0-9-]+$/.test(label??''))throw new Error('unique label required');
const dir=path.join(base,'final-f-commands',label);fs.mkdirSync(dir,{recursive:false});
const state=()=>fs.readFileSync(path.join(root,'.writer/state.json'));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const before=state();fs.writeFileSync(path.join(dir,'state-before.json'),before,{flag:'wx'});
const entry=path.join(root,'.writer/tool/bin/ai-writer.mjs');
const argv=[entry,...args,'--project',root];
fs.writeFileSync(path.join(dir,'command.json'),JSON.stringify({executable:process.execPath,argv,cwd:process.cwd(),at:new Date().toISOString()},null,2)+'\n',{flag:'wx'});
const r=spawnSync(process.execPath,argv,{cwd:root,encoding:null,maxBuffer:32*1024*1024});
fs.writeFileSync(path.join(dir,'stdout.txt'),r.stdout??Buffer.alloc(0),{flag:'wx'});
fs.writeFileSync(path.join(dir,'stderr.txt'),r.stderr??Buffer.alloc(0),{flag:'wx'});
const after=state();fs.writeFileSync(path.join(dir,'state-after.json'),after,{flag:'wx'});
const result={label,status:r.status,signal:r.signal,error:r.error?.message??null,state_before_sha256:sha(before),state_after_sha256:sha(after)};
fs.writeFileSync(path.join(dir,'result.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
process.stdout.write(r.stdout??'');process.stderr.write(r.stderr??'');console.log(JSON.stringify(result));
process.exitCode=r.status??1;
