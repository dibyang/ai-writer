import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {createRunner} from './command-runner.mjs';
const base='acceptance/20261016-hundred',stage=`${base}/recall-priority-real66`,project=path.resolve(base,'checkpoints/revision-b/files');
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const stateFile=path.join(project,'.writer/state.json'),beforeHash=sha(stateFile),runner=createRunner(stage);
const args=['recall','--project',project,'--query','T_PAGE_PAIR','--limit','1'];
runner.run(process.execPath,[path.resolve('bin/ai-writer.mjs'),...args],'before-v2');
assert.equal(sha(stateFile),beforeHash);
runner.run(process.execPath,[path.resolve(base,'candidate-v3-recall/bin/ai-writer.mjs'),...args],'after-v3');
assert.equal(sha(stateFile),beforeHash);
const before=runner.json('before-v2'),after=runner.json('after-v3');
assert.equal(before.matches.length,1);assert.equal(before.matches[0].id,'T_PUBLIC_USE');
assert.equal(after.matches.length,1);assert.equal(after.matches[0].id,'T_PAGE_PAIR');
assert.equal(before.total,after.total);assert.equal(before.omitted,after.omitted);
const result={at:new Date().toISOString(),ok:true,scope:'Real frozen 66-chapter book, read-only exact-ID result priority; not a speed benchmark or integrated acceptance',revision:197,state_sha256:beforeHash,before_first:before.matches[0].id,after_first:after.matches[0].id,total:after.total,omitted:after.omitted,main_lib_sha256:sha('lib/longform.mjs'),candidate_lib_sha256:sha(`${base}/candidate-v3-recall/lib/longform.mjs`)};
fs.writeFileSync(`${stage}/result.json`,JSON.stringify(result,null,2)+'\n',{flag:'wx'});console.log(JSON.stringify(result));
