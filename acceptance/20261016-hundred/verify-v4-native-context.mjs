import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {isDeepStrictEqual} from 'node:util';
const base=path.resolve('acceptance/20261016-hundred'),phase=path.join(base,'final-review'),root=path.resolve('.'),work=path.join(base,'works/潮汐信号');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const target=path.join(base,'integration-documentation/native-context-proof.json');
assert(!fs.existsSync(target));
assert.equal(read(path.join(phase,'process-result.json')).exit_code,0);
const audit=read(path.join(base,'audits/final-review.json'));assert(audit.ok&&audit.units===100);
const sourceFile=path.join(base,'source-baseline-v4.json'),source=read(sourceFile);
for(const r of source.files)assert.equal(hash(path.join(root,r.file)),r.sha256,r.file);
const expected=source.files.find(r=>r.file.replaceAll('\\','/')==='lib/longform.mjs').sha256;
assert.equal(hash(path.join(work,'.writer/tool/lib/longform.mjs')),expected);
const start=read(path.join(phase,'observed-start.json'));
assert.equal(start.source_baseline_sha256,hash(sourceFile));
const observed=Object.entries(start.product_sources).filter(([p])=>p.replaceAll('\\','/').endsWith('/lib/longform.mjs'));
assert.equal(observed.length,2);assert(observed.every(([,sha])=>sha===expected));
const activation=read(path.join(base,'integration-documentation/activated.json'));
const proof=read(path.join(base,'input-bindings/final-review/proof.json'));assert(proof.ok);
const index=fs.readFileSync(path.join(phase,'commands/index.jsonl'),'utf8').split(/\r?\n/).filter(Boolean).map(JSON.parse);
const contexts=index.filter(c=>c.exit_code===0&&c.argv?.[0]?.replaceAll('\\','/').endsWith('/bin/ai-writer.mjs')&&c.argv[1]==='context'&&!c.argv.includes('--help')).map(command=>({command,packet:read(command.files.stdout)}));
const bindings=[];
for(const r of proof.rows){
 const input=read(r.input);
 const found=contexts.find(({packet:p})=>p.ok&&p.unit===r.unit&&p.revision===input.expected_revision&&isDeepStrictEqual(p.source_hashes,input.source_hashes));
 if(!found)continue;
 const {command,packet}=found,text=packet.continuity?.instruction;
 assert.equal(typeof text,'string');
 for(const phrase of ['无人物条目表示未登记','追踪用的章节号和账本ID只供定位','召回摘要不能代替相关正文复读'])assert(text.includes(phrase),phrase);
 assert(Date.parse(command.started_at)>=Date.parse(activation.at));
 assert([path.join(root,'bin/ai-writer.mjs'),path.join(work,'.writer/tool/bin/ai-writer.mjs')].includes(path.resolve(command.argv[0])));
 bindings.push({unit:r.unit,expected_revision:input.expected_revision,consumed_state_sha256:input.source_hashes['.writer/state.json'],input_sha256:hash(r.input),actual_cli_metadata:command.files.metadata,actual_stdout:command.files.stdout,stdout_sha256:hash(command.files.stdout),instruction:text,started_at:command.started_at});
}
assert(bindings.length,'A real post-rewind context with the final input sources must exist');
const result={at:new Date().toISOString(),ok:true,scope:'Actual successful final native CLI context text tied to inputs consumed by formal records, plus before/after product source hashes. Presence of guidance does not establish literary effect or automatic semantic detection.',source_files:source.files.length,source_manifest_sha256:hash(sourceFile),main_and_embedded_longform_sha256:expected,observed_start_sha256:hash(path.join(phase,'observed-start.json')),bindings};
fs.writeFileSync(target,JSON.stringify(result,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({ok:true,bindings:bindings.length,units:bindings.map(r=>r.unit),source_files:source.files.length}));
