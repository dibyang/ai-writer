import fs from 'node:fs';
import path from 'node:path';
import {createRunner} from './command-runner.mjs';
const base='acceptance/20261016-hundred',stage=base+'/mixed-drift-before',work=path.resolve(stage+'/work');
if(fs.existsSync(stage))throw Error('Preserve prior evidence');
