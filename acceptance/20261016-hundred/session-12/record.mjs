import fs from 'node:fs';
import {runner,cli,project,stage,hash} from './workflow.mjs';
const unit=Number(process.argv[2]);
const input=JSON.parse(fs.readFileSync(stage+`/record-${unit}-before.json`));
const payload=JSON.parse(fs.readFileSync(stage+`/changes-${unit}.json`));
const current=JSON.parse(fs.readFileSync(stage+`/context-${unit}.json`));
const state=JSON.parse(fs.readFileSync(project+'/.writer/state.json'));
const snap=state.snapshot??state.current;
if(!snap)throw Error('No current snapshot: '+Object.keys(state));
const past=(fresh,old)=>old?fresh+'；历史有效信息（以下按原章时点，不作当前状态）：'+old:fresh;
input.summary=payload.summary;input.changes=payload.changes;
for(const [name,fresh]of Object.entries(input.changes.characters??{}))input.changes.characters[name]=past(fresh,snap.characters?.[name]);
for(const [id,entry]of Object.entries(input.changes.ledger??{}))for(const [name,fresh]of Object.entries(entry.character_known??{}))entry.character_known[name]=past(fresh,snap.ledger?.[id]?.character_known?.[name]);
const f=project+'/'+input.draft;const text=fs.readFileSync(f,'utf8');
const han=(text.replace(/^\s*#+.*$/gm,'').match(/\p{Script=Han}/gu)??[]).length;
if(han<2400||han>3200)throw Error('Han out of range: '+han);
fs.writeFileSync(stage+`/record-${unit}.json`,JSON.stringify(input,null,2)+'\n',{flag:'wx'});
fs.appendFileSync(stage+'/reading.jsonl',JSON.stringify({at:new Date().toISOString(),path:input.draft,sha256:hash(f),range:`full:1-${text.split(/\r?\n/).length}`,purpose:`第${unit}章完成后完整模型自检`,method:'actual full text inspection in model context'})+'\n');
const r=cli(`record-${unit}-cli`,['record','--input',stage+`/record-${unit}.json`]);console.log(r.stdout);console.error(r.stderr);if(r.exit_code!==0)process.exit(r.exit_code??1);
const check=cli(`check-${unit}-cli`,['check']);console.log(check.stdout);console.error(check.stderr);
console.log(JSON.stringify({unit,han,draft_sha256:hash(f),state_sha256:hash(project+'/.writer/state.json'),elapsed_s:(Date.now()-Date.parse(JSON.parse(fs.readFileSync(stage+'/start.json')).started_at))/1000}));process.exitCode=check.exit_code??1;
