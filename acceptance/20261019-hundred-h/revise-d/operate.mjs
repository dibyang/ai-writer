import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url)), H=path.dirname(dir);
const session=JSON.parse(fs.readFileSync(path.join(H,'revise-a/session.json')));
const [label,target,...args]=process.argv.slice(2);
if(!/^revise-d-[a-z0-9-]+$/.test(label)) throw Error('Unique revise-d label required');
const project=target==='main'?path.join(H,'work'):target==='branch'?session.workspace:null;
if(!project) throw Error('main or branch required');
const actual=args.map(x=>x==='TOKEN'?session.token:x==='ID'?session.id:x);
const r=spawnSync(process.execPath,[path.join(H,'capture.mjs'),label,process.execPath,path.join(H,'work/.writer/tool/bin/ai-writer.mjs'),...actual,'--project',project],{encoding:'utf8',windowsHide:true});
const command=path.join(H,'commands',label);
if(!fs.existsSync(path.join(command,'result.json'))) throw Error(r.stderr||r.stdout||'Capture did not complete');
const meta=JSON.parse(fs.readFileSync(path.join(command,'result.json')));
fs.appendFileSync(path.join(dir,'commands.jsonl'),JSON.stringify({label,target,command:args.map(x=>x==='TOKEN'?'[original local token]':x),exit_code:meta.exit_code,before:meta.before_state_sha256,after:meta.after_state_sha256})+'\n');
console.log(JSON.stringify({label,exit_code:meta.exit_code,before:meta.before_state_sha256,after:meta.after_state_sha256}));
if(meta.exit_code!==0) console.log(fs.readFileSync(path.join(command,'stderr.raw.txt'),'utf8'));
process.exitCode=meta.exit_code??1;
